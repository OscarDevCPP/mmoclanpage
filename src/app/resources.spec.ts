import { TestBed } from '@angular/core/testing';
import { provideRouter, Router } from '@angular/router';
import { RouterTestingHarness } from '@angular/router/testing';
import { routes } from './app.routes';
import { Resources } from './resources';
import { PresentationState } from './presentation-state';

const key = 'black-talon.compendio.presentation.v1';
describe('El Compendio', () => {
  beforeEach(() => { localStorage.clear(); vi.spyOn(window, 'scrollTo').mockImplementation(() => {}); });
  afterEach(() => { localStorage.clear(); vi.restoreAllMocks(); });
  it('primera visita, salto, índice, guía, regreso y repetición', async () => {
    TestBed.configureTestingModule({ providers: [provideRouter(routes)] });
    const harness = await RouterTestingHarness.create();
    let component = await harness.navigateByUrl('/compendio', Resources);
    const state = TestBed.inject(PresentationState);
    expect(state.active()).toBe(true);
    expect(harness.routeNativeElement?.textContent).toContain('Escena 1/9');
    window.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight' }));
    expect(component.index()).toBe(1);
    (harness.routeNativeElement?.querySelector('[aria-label="Saltar al Compendio"]') as HTMLButtonElement).click();
    harness.detectChanges();
    expect(localStorage.getItem(key)).toBe('seen');
    expect(state.active()).toBe(false);
    const page = harness.routeNativeElement as HTMLElement;
    expect(page.querySelector('.compendium')?.classList.contains('cinema-active')).toBe(false);
    expect(page.textContent).toContain('Recopilación de conocimientos prácticos con mucho cariño para la comunidad');
    expect(page.querySelector('nav')?.getAttribute('aria-label')).toBe('Contenido del Compendio');
    const details = [...page.querySelectorAll<HTMLDetailsElement>('.compendium details')];
    expect(details).toHaveLength(2);
    expect(details[0].open).toBe(false);
    expect(details[0].classList.contains('category')).toBe(true);
    details[0].open = true;
    const toggle = page.querySelector<HTMLButtonElement>('.chapter-toggle')!;
    const topics = page.querySelector<HTMLUListElement>('#pvp-introduction-topics')!;
    const eye = page.querySelector<HTMLAnchorElement>('.chapter-view')!;
    expect(toggle.getAttribute('aria-controls')).toBe(topics.id);
    expect(toggle.getAttribute('aria-expanded')).toBe('false');
    expect(topics.hidden).toBe(true);
    expect(eye.getAttribute('aria-label')).toBe('Ver Introducción al competitivo');
    expect(eye.title).toBe('Ver Introducción al competitivo');
    expect(eye.pathname).toBe('/compendio/pvp/fundamentos');
    expect(eye.hash).toBe('');
    expect(eye.querySelector('svg')?.getAttribute('aria-hidden')).toBe('true');
    expect(eye.querySelector('svg')?.getAttribute('focusable')).toBe('false');
    expect(eye.textContent?.trim()).toBe('');
    toggle.click(); await harness.fixture.whenStable();
    expect(toggle.getAttribute('aria-expanded')).toBe('true');
    expect(topics.hidden).toBe(false);
    toggle.click(); await harness.fixture.whenStable();
    expect(toggle.getAttribute('aria-expanded')).toBe('false');
    expect(topics.hidden).toBe(true);
    toggle.click(); await harness.fixture.whenStable();
    expect(page.querySelectorAll('summary button, summary a')).toHaveLength(0);
    const index = page.querySelector('.compendium nav')!;
    expect(index.textContent).not.toMatch(/Pendiente|Parcial|Eventos del juego/i);
    expect(index.textContent).toContain('Guías de PvE');
    const pveToggle = page.querySelector<HTMLButtonElement>('#pve .chapter-toggle[aria-controls="pve-pillars-topics"]')!;
    expect(pveToggle.textContent?.trim()).toBe('LOS SEIS PILARES, FARMEO DE GYMS (AVANZADO)');
    const pveTopics = page.querySelector<HTMLUListElement>('#pve-pillars-topics')!;
    expect(pveTopics.hidden).toBe(true);
    pveToggle.click(); await harness.fixture.whenStable();
    expect(pveToggle.getAttribute('aria-expanded')).toBe('true');
    expect([...pveTopics.querySelectorAll('a')].map(a => a.hash)).toEqual(['#preparacion', '#equipo', '#estrategia', '#basica']);
    expect([...pveTopics.querySelectorAll('a')].map(a => a.textContent?.trim())).toEqual(['Introducción', 'El equipo', 'La idea principal', 'Ruta básica y avanzadas']);
    expect(page.querySelector<HTMLAnchorElement>('#pve .chapter-view')?.hash).toBe('');
    expect(index.querySelector<HTMLAnchorElement>('a[href="/compendio/pve/seis-pilares"]')).toBeTruthy();
    const links = [...topics.querySelectorAll<HTMLAnchorElement>('a')];
    expect(links.map(link => [link.textContent?.trim(), link.hash])).toEqual([
      ['Formas de jugar al PvP', '#introduccion-modalidades'], ['Lo esencial antes de crear un equipo', '#introduccion-tipos'],
      ['Construcción de equipos', '#introduccion-sinergia'], ['La idea detrás de cada combate', '#introduccion-combate'],
    ]);
    expect(links.every(a => a.pathname === '/compendio/pvp/fundamentos' && a.hash.startsWith('#introduccion-'))).toBe(true);
    links[0].click(); await harness.fixture.whenStable();
    expect(TestBed.inject(Router).url).toBe('/compendio/pvp/fundamentos#introduccion-modalidades');
    expect(state.active()).toBe(false);
    component = await harness.navigateByUrl('/compendio', Resources);
    await harness.fixture.whenStable();
    const rootLink = harness.routeNativeElement!.querySelector<HTMLAnchorElement>('.chapter-view')!;
    rootLink.click(); await harness.fixture.whenStable();
    expect(TestBed.inject(Router).url).toBe('/compendio/pvp/fundamentos');
    component = await harness.navigateByUrl('/compendio', Resources);
    await harness.fixture.whenStable(); harness.detectChanges();
    expect(component.guide()).toBe(true);
    expect(state.active()).toBe(false);
    const replay = harness.routeNativeElement?.querySelector<HTMLButtonElement>('button[aria-label="Volver a ver la presentación del Compendio"]');
    expect(replay).toBeTruthy();
    expect(replay?.getAttribute('title')).toBe('Volver a ver la presentación del Compendio');
    expect(replay?.getAttribute('data-tooltip')).toBe('Volver a ver la presentación del Compendio');
    expect(replay?.querySelector('svg')?.getAttribute('aria-hidden')).toBe('true');
    expect(replay?.textContent?.trim()).toBe('');
    replay!.click();
    harness.detectChanges(); expect(state.active()).toBe(true); expect(component.index()).toBe(0);
    component.finish(); harness.detectChanges(); expect(state.active()).toBe(false);
    await harness.navigateByUrl('/'); expect(state.active()).toBe(false);
  });
  it('conserva el comportamiento si el almacenamiento está bloqueado', async () => {
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw Error('blocked'); });
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw Error('blocked'); });
    TestBed.configureTestingModule({ providers: [provideRouter([])] });
    const fixture = TestBed.createComponent(Resources); await fixture.whenStable();
    expect(fixture.componentInstance.guide()).toBe(false);
    fixture.componentInstance.finish(); expect(fixture.componentInstance.guide()).toBe(true);
    expect(TestBed.inject(PresentationState).active()).toBe(false);
    fixture.componentInstance.replay(); expect(TestBed.inject(PresentationState).active()).toBe(true);
    fixture.destroy(); expect(TestBed.inject(PresentationState).active()).toBe(false);
  });
});
